package com.parasoft.jscov;

import com.parasoft.jscov.i18n.CommonMessages;
import com.parasoft.xtest.common.api.MessageSeverity;
import com.parasoft.xtest.common.api.console.IConsole;
import com.parasoft.xtest.coverage.all.api.ICoverageDataEngine;
import com.parasoft.xtest.coverage.all.api.ICoverageOptions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;
import java.util.ResourceBundle;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

class JavascriptCoverageDataEngineTest {

    private static final String APP_VALUE_NAME = "%JSCOV_STATIC_COVERAGE_JSON_DIR%";
    private static final String APP_DESCRIPTION =
            "Specifies the directory containing static coverage JSON files generated by JavaScript instrumentation.";
    private static final String RUNTIME_UNSUPPORTED_MESSAGE =
            "JavaScript Coverage does not support runtime coverage. Remove the -runtime option.";
    private static final String IMPACTED_UNSUPPORTED_MESSAGE =
            "JavaScript Coverage does not support the impacted command yet.";
    private static final String MERGE_UNSUPPORTED_MESSAGE =
            "JavaScript Coverage does not support the merge command yet.";
    private static final String FILTER_UNSUPPORTED_MESSAGE =
            "JavaScript Coverage does not support -include or -exclude yet.";

    @Test
    void getCLICommandName_usesParasoftJarName() {
        assertEquals("java -jar parasoft-jscov.jar",
                new JavascriptCoverageDataEngine().getCLICommandName());
    }

    @Test
    void getEngineOptions_overridesAppHelpForCoverageAndImpacted() {
        ICoverageDataEngine.CommandLineArgument[] options = new JavascriptCoverageDataEngine().getEngineOptions();

        assertEquals(1, options.length);
        ICoverageDataEngine.CommandLineArgument appOption = options[0];
        assertEquals("-app", appOption.key);
        assertEquals(APP_VALUE_NAME, appOption.valueName);
        assertArrayEquals(new ICoverageOptions.CoverageCommand[]{
                ICoverageOptions.CoverageCommand.coverage,
                ICoverageOptions.CoverageCommand.impacted
        }, appOption.commands);
        assertEquals(ICoverageDataEngine.ArgumentType.Single, appOption.type);
        assertArrayEquals(new String[]{APP_DESCRIPTION}, appOption.description);
    }

    @Test
    void permanentUnsupportedMessagesAreProvidedByCommonMessages() {
        ResourceBundle messages = ResourceBundle.getBundle(
                "com.parasoft.jscov.i18n.res.messages", Locale.getDefault());

        assertEquals(messages.getString("TESTMAP_UNSUPPORTED_MESSAGE"),
                CommonMessages.TESTMAP_UNSUPPORTED_MESSAGE);
        assertEquals(messages.getString("COMPARE_UNSUPPORTED_MESSAGE"),
                CommonMessages.COMPARE_UNSUPPORTED_MESSAGE);
        assertEquals(messages.getString("INVALID_APPLICATION_DIRECTORY_MESSAGE"),
                CommonMessages.INVALID_APPLICATION_DIRECTORY_MESSAGE);
        assertEquals(messages.getString("APPLICATION_PARAMETER_DESCRIPTION"),
                CommonMessages.APPLICATION_PARAMETER_DESCRIPTION);
    }

    @Test
    void verifyOptions_allowsCoverageWithoutUnsupportedOptions() {
        ICoverageOptions options = optionsFor(ICoverageOptions.CoverageCommand.coverage);

        assertTrue(new JavascriptCoverageDataEngine().verifyOptions(options, mock(IConsole.class)));
    }

    @Test
    void verifyOptions_acceptsApplicationDirectory(@TempDir Path applicationDirectory) {
        ICoverageOptions options = optionsFor(ICoverageOptions.CoverageCommand.coverage);
        when(options.getApplicationUnderTest()).thenReturn(applicationDirectory);

        assertTrue(new JavascriptCoverageDataEngine().verifyOptions(options, mock(IConsole.class)));
    }

    @Test
    void verifyOptions_rejectsEmptyApplicationValue() {
        ICoverageOptions options = optionsFor(ICoverageOptions.CoverageCommand.coverage);
        IConsole console = mock(IConsole.class);
        when(options.getApplicationUnderTest()).thenReturn(Path.of(""));

        assertFalse(new JavascriptCoverageDataEngine().verifyOptions(options, console));
        verify(console).writeln(CommonMessages.INVALID_APPLICATION_DIRECTORY_MESSAGE, MessageSeverity.HIGH);
    }

    @Test
    void verifyOptions_rejectsApplicationFile(@TempDir Path temporaryDirectory) throws IOException {
        Path applicationFile = Files.createFile(temporaryDirectory.resolve("static_coverage.json"));
        ICoverageOptions options = optionsFor(ICoverageOptions.CoverageCommand.coverage);
        IConsole console = mock(IConsole.class);
        when(options.getApplicationUnderTest()).thenReturn(applicationFile);

        assertFalse(new JavascriptCoverageDataEngine().verifyOptions(options, console));
        verify(console).writeln(CommonMessages.INVALID_APPLICATION_DIRECTORY_MESSAGE, MessageSeverity.HIGH);
    }

    @Test
    void verifyOptions_allowsHelp() {
        ICoverageOptions options = optionsFor(ICoverageOptions.CoverageCommand.help);
        IConsole console = mock(IConsole.class);
        when(options.getRuntimeCoverageData()).thenReturn(Path.of("runtime-data"));
        when(options.getIncludes()).thenReturn(new String[]{"src/**"});
        when(options.getExcludes()).thenReturn(new String[]{"test/**"});

        assertTrue(new JavascriptCoverageDataEngine().verifyOptions(options, console));
        verifyNoInteractions(console);
    }

    @Test
    void verifyOptions_rejectsImpactedUntilImplemented() {
        assertRejectedCommand(ICoverageOptions.CoverageCommand.impacted, IMPACTED_UNSUPPORTED_MESSAGE);
    }

    @Test
    void verifyOptions_rejectsMergeUntilImplemented() {
        assertRejectedCommand(ICoverageOptions.CoverageCommand.merge, MERGE_UNSUPPORTED_MESSAGE);
    }

    @Test
    void verifyOptions_rejectsTestmapPermanently() {
        assertRejectedCommand(ICoverageOptions.CoverageCommand.testmap, CommonMessages.TESTMAP_UNSUPPORTED_MESSAGE);
    }

    @Test
    void verifyOptions_rejectsComparePermanently() {
        assertRejectedCommand(ICoverageOptions.CoverageCommand.compare, CommonMessages.COMPARE_UNSUPPORTED_MESSAGE);
    }

    @Test
    void verifyOptions_rejectsIncludeUntilFilteringIsImplemented() {
        ICoverageOptions options = optionsFor(ICoverageOptions.CoverageCommand.coverage);
        IConsole console = mock(IConsole.class);
        when(options.getIncludes()).thenReturn(new String[]{"src/**"});

        assertFalse(new JavascriptCoverageDataEngine().verifyOptions(options, console));
        verify(console).writeln(FILTER_UNSUPPORTED_MESSAGE, MessageSeverity.HIGH);
    }

    @Test
    void verifyOptions_rejectsExcludeUntilFilteringIsImplemented() {
        ICoverageOptions options = optionsFor(ICoverageOptions.CoverageCommand.coverage);
        IConsole console = mock(IConsole.class);
        when(options.getExcludes()).thenReturn(new String[]{"test/**"});

        assertFalse(new JavascriptCoverageDataEngine().verifyOptions(options, console));
        verify(console).writeln(FILTER_UNSUPPORTED_MESSAGE, MessageSeverity.HIGH);
    }

    @Test
    void verifyOptions_rejectsRuntimeCoverageAndReportsThroughConsole() {
        ICoverageOptions options = optionsFor(ICoverageOptions.CoverageCommand.coverage);
        IConsole console = mock(IConsole.class);
        when(options.getRuntimeCoverageData()).thenReturn(Path.of("runtime-data"));

        assertFalse(new JavascriptCoverageDataEngine().verifyOptions(options, console));
        verify(console).writeln(RUNTIME_UNSUPPORTED_MESSAGE, MessageSeverity.HIGH);
    }

    private static ICoverageOptions optionsFor(ICoverageOptions.CoverageCommand command) {
        ICoverageOptions options = mock(ICoverageOptions.class);
        when(options.getCommand()).thenReturn(command);
        when(options.getRuntimeCoverageData()).thenReturn(null);
        when(options.getIncludes()).thenReturn(null);
        when(options.getExcludes()).thenReturn(null);
        when(options.getApplicationUnderTest()).thenReturn(null);
        return options;
    }

    private static void assertRejectedCommand(ICoverageOptions.CoverageCommand command, String message) {
        ICoverageOptions options = optionsFor(command);
        IConsole console = mock(IConsole.class);

        assertFalse(new JavascriptCoverageDataEngine().verifyOptions(options, console));
        verify(console).writeln(message, MessageSeverity.HIGH);
    }
}
